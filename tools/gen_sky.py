"""Generates templates/_sky.html: the animated night skyline in the top bar.
Layers: stars (twinkle) -> far houses (slow drift) -> mist -> near houses with windows (some fade on/off).
Run from the project folder:  python tools/gen_sky.py"""
import random

random.seed(11)
W, H = 1600, 200
X0, X1 = -80, W + 80          # wider than the view so the drift never shows an edge


def houses(base, hmin, hmax, wall_cols, trim, windows, lit_ratio=0.5):
    out, x = [], X0
    while x < X1:
        w = random.choice([64, 76, 90, 104, 120])
        h = random.uniform(hmin, hmax)
        top = base - h
        wall = random.choice(wall_cols)          # a class name: colors come from the CSS (light / dark)
        out.append(f'<rect class="{wall}" x="{x}" y="{top:.0f}" width="{w}" height="{h + 4:.0f}"/>')
        n = max(3, w // 12); step = w / n
        pts = " ".join(f"{x + i * step:.0f},{top:.0f} {x + i * step + step / 2:.0f},{top - 7:.0f}" for i in range(n))
        out.append(f'<polyline class="{wall}" points="{pts} {x + w},{top:.0f}"/>')
        out.append(f'<rect class="{trim}" x="{x}" y="{top + 6:.0f}" width="{w}" height="2.5" opacity=".5"/>')
        if windows:
            rows = max(1, int((h - 26) // 26)); cols = max(1, w // 30)
            for r in range(rows):
                for c in range(cols):
                    wx = x + (w / cols) * c + (w / cols) / 2 - 5
                    wy = top + 18 + r * 26
                    if random.random() < lit_ratio:
                        cls = "win"
                        if random.random() < 0.32:
                            cls += f" tw tw{random.randint(1, 6)}"     # fades off now and then
                        out.append(f'<rect class="{cls}" x="{wx:.0f}" y="{wy:.0f}" width="10" height="13" rx="5"/>')
                    else:
                        cls = "win-off"
                        if random.random() < 0.18:
                            cls += f" tn tn{random.randint(1, 4)}"     # lights up now and then
                        out.append(f'<rect class="{cls}" x="{wx:.0f}" y="{wy:.0f}" width="10" height="13" rx="5"/>')
        x += w + random.choice([0, 0, 4, 10])
        if windows and random.random() < 0.3 and x < X1:
            px, ph = x + 8, random.uniform(42, 60)
            out.append(f'<path class="palm" d="M{px},{base} q3,-{ph / 2:.0f} 1,-{ph:.0f}"/>')
            tx, ty = px + 1, base - ph
            for a, b in [(-20, -5), (-15, 7), (20, -5), (15, 7), (-5, -14), (6, -12)]:
                out.append(f'<path class="palm" d="M{tx},{ty:.0f} q{a / 2},{b - 8} {a},{b}"/>')
            x += 20
    return "".join(out)


stars = []
for _ in range(60):
    stars.append(f'<circle class="star st{random.randint(1, 4)}" cx="{random.uniform(0, W):.0f}" '
                 f'cy="{random.uniform(6, 120):.0f}" r="{random.choice([0.8, 1, 1.2, 1.5])}"/>')

far = houses(196, 70, 128, ["fw1", "fw2", "fw3"], "ftrim", windows=False)
near = houses(200, 48, 100, ["nw1", "nw2", "nw3"], "ntrim", windows=True, lit_ratio=0.45)

svg = f'''<svg class="sky-svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax slice" aria-hidden="true" focusable="false">
<defs><linearGradient id="sky-mist" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#3b5169" stop-opacity="0"/><stop offset="1" stop-color="#3b5169" stop-opacity=".55"/></linearGradient></defs>
<g class="sky-stars">{"".join(stars)}</g>
<g class="sky-px sky-px-far"><g class="sky-far">{far}</g></g>
<rect x="{X0}" y="110" width="{X1 - X0}" height="90" fill="url(#sky-mist)"/>
<g class="sky-px sky-px-near"><g class="sky-near">{near}</g></g>
</svg>'''
open("templates/_sky.html", "w", encoding="utf-8").write(
    "{# Generated by tools/gen_sky.py - edit the script, not this file. #}\n" + svg + "\n")
print("ok", len(svg), "bytes")
